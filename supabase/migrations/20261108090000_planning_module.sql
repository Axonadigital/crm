-- =============================================================================
-- 1. IDÉBANK
-- =============================================================================
CREATE TABLE IF NOT EXISTS planning_ideas (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  notes text,
  status text NOT NULL DEFAULT 'new',
  sales_id bigint REFERENCES sales(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT chk_planning_ideas_status
    CHECK (status IN ('new', 'planned', 'dropped'))
);

-- =============================================================================
-- 2. MÅL
-- =============================================================================
CREATE TABLE IF NOT EXISTS planning_goals (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  description text,
  unit text,
  current_value numeric NOT NULL DEFAULT 0,
  target_value numeric,
  deadline date,
  status text NOT NULL DEFAULT 'active',
  sales_id bigint REFERENCES sales(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT chk_planning_goals_status
    CHECK (status IN ('active', 'achieved', 'dropped'))
);

-- =============================================================================
-- 3. PROJEKT
-- =============================================================================
CREATE TABLE IF NOT EXISTS planning_projects (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  description text,
  goal_id bigint REFERENCES planning_goals(id) ON DELETE SET NULL,
  owner_id bigint REFERENCES sales(id),
  status text NOT NULL DEFAULT 'planned',
  estimate_hours numeric,
  due_date date,
  notes text,
  sales_id bigint REFERENCES sales(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT chk_planning_projects_status
    CHECK (status IN ('planned', 'active', 'paused', 'done'))
);

-- =============================================================================
-- 4. UPPGIFTER
-- =============================================================================
CREATE TABLE IF NOT EXISTS planning_tasks (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  project_id bigint REFERENCES planning_projects(id) ON DELETE SET NULL,
  assignee_id bigint REFERENCES sales(id),
  status text NOT NULL DEFAULT 'todo',
  estimate_hours numeric,
  planned_date date,
  notes text,
  sales_id bigint REFERENCES sales(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT chk_planning_tasks_status
    CHECK (status IN ('todo', 'doing', 'done'))
);

CREATE INDEX IF NOT EXISTS idx_planning_projects_goal ON planning_projects(goal_id);
CREATE INDEX IF NOT EXISTS idx_planning_tasks_project ON planning_tasks(project_id);
CREATE INDEX IF NOT EXISTS idx_planning_tasks_assignee ON planning_tasks(assignee_id);

-- =============================================================================
-- 5. TRIGGERS (updated_at + auto-satt sales_id)
-- =============================================================================
CREATE OR REPLACE FUNCTION set_planning_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SET search_path TO '';

DO $$
DECLARE
  t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['planning_ideas', 'planning_goals', 'planning_projects', 'planning_tasks']
  LOOP
    EXECUTE format(
      'CREATE TRIGGER %I BEFORE UPDATE ON %I FOR EACH ROW EXECUTE FUNCTION set_planning_updated_at()',
      t || '_updated_at_trigger', t
    );
    EXECUTE format(
      'CREATE TRIGGER %I BEFORE INSERT ON %I FOR EACH ROW EXECUTE FUNCTION set_sales_id_default()',
      'set_' || t || '_sales_id_trigger', t
    );
  END LOOP;
END $$;

