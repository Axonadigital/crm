CREATE EXTENSION IF NOT EXISTS pg_cron;

-- Byt ut de gamla "gör allt i en körning"-jobben mot kö-mönstret.
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM cron.job WHERE jobname = 'monthly-website-snapshots') THEN
    PERFORM cron.unschedule('monthly-website-snapshots');
  END IF;
  IF EXISTS (SELECT 1 FROM cron.job WHERE jobname = 'monthly-reports') THEN
    PERFORM cron.unschedule('monthly-reports');
  END IF;
END $$;

-- 5:e i månaden (inte 1:a) — Google Search Console har upp till 3 dygns
-- eftersläpning, så vi ger en extra dags marginal utöver värsta scenariot
-- innan vi läser data för den fullständiga föregående månaden.
SELECT cron.schedule(
  'pipeline-seed-monthly',
  '0 6 5 * *',
  $$SELECT public.seed_monthly_pipeline_queue();$$
);

SELECT cron.schedule(
  'pipeline-tick-snapshot',
  '*/5 * * * *',
  $$SELECT public.run_pipeline_tick('snapshot');$$
);

SELECT cron.schedule(
  'pipeline-tick-report',
  '*/5 * * * *',
  $$SELECT public.run_pipeline_tick('report');$$
);

SELECT cron.schedule(
  'pipeline-stuck-alert',
  '0 9 * * *',
  $$SELECT public.check_stuck_pipeline_items();$$
);
