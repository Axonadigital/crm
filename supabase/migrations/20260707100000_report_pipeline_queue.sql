-- Migration: report_pipeline_queue + kö-baserad månadscron
-- Created: 2026-07-07
-- Description: Ersätter de två "gör allt i en enda edge-anrop"-cronjobben
--              (monthly-website-snapshots, monthly-reports) med en kö-tabell +
--              återkommande "tick". Bakgrund: ett enda cron-anrop som skulle
--              analysera alla kunder i en körning hann inte klart innan
--              Supabase-funktionens tidsgräns slog till — en del kunder
--              bearbetades aldrig, helt tyst. Kö-mönstret skalar till
--              godtyckligt antal kunder utan kodändring: ett litet antal
--              rader plockas upp var 5:e minut tills kön är tom.
--              Helt additiv migration — inga DROP/ALTER på befintliga objekt
--              förutom att de två gamla cron-jobben schemaläggs om (samma
--              mekanism, cron.unschedule/cron.schedule, ingen datadestruktion).

CREATE TABLE IF NOT EXISTS "public"."report_pipeline_queue" (
  "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "company_id" bigint NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
  "period_start" date NOT NULL,
  "period_end" date NOT NULL,
  -- snapshot: analysera hemsidan (analyze_website). report: generera kundrapport
  -- (generate_monthly_reports) — skapas automatiskt när snapshot-steget lyckas.
  "stage" text NOT NULL CHECK (stage IN ('snapshot', 'report')),
  -- pending: väntar på att plockas upp. processing: ett tick håller på just nu
  -- (självläker till pending igen om det tar >15 min, se claim_pipeline_queue_batch).
  -- done / failed: slutligt resultat för perioden.
  "status" text NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'processing', 'done', 'failed')),
  "attempts" integer NOT NULL DEFAULT 0,
  "error" text,
  "claimed_at" timestamp with time zone,
  "completed_at" timestamp with time zone,
  "created_at" timestamp with time zone DEFAULT now() NOT NULL
);

ALTER TABLE "public"."report_pipeline_queue" ENABLE ROW LEVEL SECURITY;

-- Samma öppna mönster som monthly_reports — hela teamet ska kunna se/åtgärda
-- misslyckade rader i CRM:t. Edge-funktionerna skriver via service role.
-- DROP+CREATE (inte bara IF NOT EXISTS) så migrationen är säker att köra om.
DROP POLICY IF EXISTS "Authenticated can view pipeline queue" ON "public"."report_pipeline_queue";
CREATE POLICY "Authenticated can view pipeline queue" ON "public"."report_pipeline_queue"
  FOR SELECT
  USING (auth.role() = 'authenticated');

DROP POLICY IF EXISTS "Authenticated can update pipeline queue" ON "public"."report_pipeline_queue";
CREATE POLICY "Authenticated can update pipeline queue" ON "public"."report_pipeline_queue"
  FOR UPDATE
  USING (auth.role() = 'authenticated')
  WITH CHECK (auth.role() = 'authenticated');

-- Identitetskolumnerna (vilken kund/period/steg raden gäller) får aldrig
-- ändras via UPDATE — bara status/error/attempts/tidsstämplar. Skyddar mot en
-- CRM-knapp (t.ex. "Kör om") som av misstag skulle skriva fel company_id.
CREATE OR REPLACE FUNCTION public.prevent_pipeline_queue_identity_change()
RETURNS trigger
LANGUAGE plpgsql
SET search_path TO ''
AS $$
BEGIN
  IF NEW.company_id <> OLD.company_id
     OR NEW.period_start <> OLD.period_start
     OR NEW.stage <> OLD.stage THEN
    RAISE EXCEPTION 'report_pipeline_queue: company_id/period_start/stage kan inte ändras efter att raden skapats';
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_pipeline_queue_identity_lock ON public.report_pipeline_queue;
CREATE TRIGGER trg_pipeline_queue_identity_lock
  BEFORE UPDATE ON public.report_pipeline_queue
  FOR EACH ROW
  EXECUTE FUNCTION public.prevent_pipeline_queue_identity_change();

-- En rad per kund, period och steg (idempotent seed + idempotent steg-övergång).
CREATE UNIQUE INDEX IF NOT EXISTS idx_pipeline_queue_company_period_stage
  ON report_pipeline_queue(company_id, period_start, stage);
CREATE INDEX IF NOT EXISTS idx_pipeline_queue_claim ON report_pipeline_queue(stage, status);
CREATE INDEX IF NOT EXISTS idx_pipeline_queue_stuck ON report_pipeline_queue(status, created_at);

